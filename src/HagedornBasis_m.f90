module HagedornBasis_m
  !!==========================================================================
  !!  HagedornBasis_m
  !!
  !!  Complete Fortran implementation of homogeneous Hagedorn wavepackets.
  !!
  !!  The module provides
  !!    * basis-shape aware packet initialization,
  !!    * admissibility checks on (Q,P),
  !!    * exact recursive evaluation of basis functions,
  !!    * analytic actions of x, p, ∇, Hessian and Laplacian,
  !!    * projection utilities between nested Hagedorn shapes,
  !!    * grid evaluation of wavepackets and analytic derivatives.
  !!
  !!  Mathematical definition
  !!    For ε > 0 and admissible matrices Q,P ∈ C^{D×D} satisfying
  !!        Q^T P - P^T Q = 0,
  !!        Q^H P - P^H Q = 2 i I,
  !!    the ground-state Hagedorn packet is
  !!        φ_0(x) = (π ε²)^(-D/4) det(Q)^(-1/2)
  !!                 exp( i/ε² [ 1/2 (x-q)^T P Q^{-1} (x-q) + p^T(x-q) + S ] ).
  !!
  !!    Higher basis functions are generated by the creation operators, and the
  !!    practical evaluation on grids is performed with the standard three-term
  !!    recurrence used in WaveBlocksND.
  !!
  !!  Operator identities implemented here
  !!      x ψ  = q ψ + sqrt(ε²/2) ( Q a† + Q̄ a ) ψ
  !!      p̂ ψ = p ψ + sqrt(ε²/2) ( P a† + P̄ a ) ψ
  !!      ∇ ψ  = (i/ε²) p̂ ψ
  !!
  !!  References
  !!    * G. A. Hagedorn, semiclassical quantum mechanics I--IV.
  !!    * E. Faou, V. Gradinaru, C. Lubich, Computing semiclassical quantum
  !!      dynamics with Hagedorn wavepackets.
  !!    * WaveBlocksND source code and documentation.
  !!==========================================================================
  USE QDUtil_m
  use HagedornLinalg_m
  use NDindex_hagedorn_m
  implicit none
  public :: Cmat_to_QP
  private

  type, public :: HagedornBasis_t
    integer :: ndim = 0
    real(KIND=Rkind) :: eps = ONE
    complex(KIND=Rkind), allocatable :: q(:)
    complex(KIND=Rkind), allocatable :: p(:)
    complex(KIND=Rkind), allocatable :: qmat(:,:)
    complex(KIND=Rkind), allocatable :: pmat(:,:)
    complex(KIND=Rkind) :: actionS = CZERO
    type(HagedornBasisShape_t) :: shape

    complex(KIND=Rkind), allocatable :: qinv(:,:)
    complex(KIND=Rkind), allocatable :: qqbar(:,:)
    complex(KIND=Rkind), allocatable :: apq(:,:)
    complex(KIND=Rkind) :: detQ = CONE
    complex(KIND=Rkind) :: sqrt_detQ = CONE

    integer :: basis_size = 0
    integer :: zero_index = 0
    integer, allocatable :: degree(:)
    integer, allocatable :: backward(:,:)
    integer, allocatable :: forward(:,:)

    logical :: admissible = .false.
    real(KIND=Rkind) :: admissibility_residual(2) = ZERO
  end type HagedornBasis_t

  public :: init_hagedorn_basis
  public :: destroy_hagedorn_basis
  public :: extend_hagedorn_shape
  public :: init_extended_hagedorn_basis
  public :: evaluate_ground_state
  public :: evaluate_basis_on_grid
  public :: evaluate_wavepacket_on_grid
  public :: evaluate_gradient_on_grid
  public :: evaluate_hessian_on_grid
  public :: evaluate_laplacian_on_grid
  public :: apply_position_operator
  public :: apply_momentum_operator
  public :: apply_gradient_operator
  public :: apply_second_derivative_operator
  public :: apply_laplacian_operator
  public :: project_coefficients
  public :: embed_coefficients
  public :: copy_hagedorn_basis

contains

  subroutine destroy_hagedorn_basis(basis)
    type(HagedornBasis_t), intent(inout) :: basis

    if (allocated(basis%q))        deallocate(basis%q)
    if (allocated(basis%p))        deallocate(basis%p)
    if (allocated(basis%qmat))     deallocate(basis%qmat)
    if (allocated(basis%pmat))     deallocate(basis%pmat)
    if (allocated(basis%qinv))     deallocate(basis%qinv)
    if (allocated(basis%qqbar))    deallocate(basis%qqbar)
    if (allocated(basis%apq))      deallocate(basis%apq)
    if (allocated(basis%degree))   deallocate(basis%degree)
    if (allocated(basis%backward)) deallocate(basis%backward)
    if (allocated(basis%forward))  deallocate(basis%forward)
    call destroy_hagedorn_shape(basis%shape)

    basis%ndim = 0
    basis%eps = ONE
    basis%actionS = CZERO
    basis%detQ = CONE
    basis%sqrt_detQ = CONE
    basis%basis_size = 0
    basis%zero_index = 0
    basis%admissible = .false.
    basis%admissibility_residual = ZERO
  end subroutine destroy_hagedorn_basis

  subroutine init_hagedorn_basis(basis, shape, q, p, qmat, pmat, actionS, eps, tol)
    type(HagedornBasis_t), intent(inout) :: basis
    type(HagedornBasisShape_t), intent(in) :: shape
    complex(KIND=Rkind), intent(in) :: q(:), p(:), qmat(:,:), pmat(:,:)
    complex(KIND=Rkind), intent(in), optional :: actionS
    real(KIND=Rkind), intent(in), optional :: eps, tol
    real(KIND=Rkind) :: atol

    call destroy_hagedorn_basis(basis)

    basis%ndim = size(q)
    if (size(p) /= basis%ndim) error stop 'init_hagedorn_basis: incompatible q/p sizes.'
    if (shape%ndim /= basis%ndim) error stop 'init_hagedorn_basis: shape dimension mismatch.'
    if (size(qmat,1) /= basis%ndim .or. size(qmat,2) /= basis%ndim) error stop 'init_hagedorn_basis: Q has wrong size.'
    if (size(pmat,1) /= basis%ndim .or. size(pmat,2) /= basis%ndim) error stop 'init_hagedorn_basis: P has wrong size.'

    allocate(basis%q(basis%ndim), basis%p(basis%ndim), basis%qmat(basis%ndim,basis%ndim), basis%pmat(basis%ndim,basis%ndim))
    basis%q = q
    basis%p = p
    basis%qmat = qmat
    basis%pmat = pmat
    if (present(actionS)) basis%actionS = actionS
    if (present(eps)) basis%eps = eps

    call copy_shape_local(basis%shape, shape)
    basis%basis_size = int(get_basis_size(shape))

    basis%qinv = matrix_inverse_c(qmat)
    basis%qqbar = matmul(basis%qinv, conjg(qmat))
    basis%apq = matmul(pmat, basis%qinv)
    basis%detQ = determinant_c(qmat)
    basis%sqrt_detQ = sqrt(basis%detQ)

    atol = ONETENTH**10
    if (present(tol)) atol = tol
    call check_hagedorn_admissibility( &
         qmat, pmat, basis%admissible, &
         basis%admissibility_residual(1), basis%admissibility_residual(2), atol)

    call build_neighbour_tables(basis)
  end subroutine init_hagedorn_basis

  subroutine copy_hagedorn_basis(dst, src)
    type(HagedornBasis_t), intent(inout) :: dst
    type(HagedornBasis_t), intent(in) :: src
    call init_hagedorn_basis(dst, src%shape, src%q, src%p, src%qmat, src%pmat, src%actionS, src%eps)
  end subroutine copy_hagedorn_basis

  subroutine init_extended_hagedorn_basis(ext_basis, basis, steps)
    type(HagedornBasis_t), intent(inout) :: ext_basis
    type(HagedornBasis_t), intent(in) :: basis
    integer, intent(in), optional :: steps
    type(HagedornBasisShape_t) :: ext_shape
    integer :: nsteps

    nsteps = 1
    if (present(steps)) nsteps = steps
    call extend_hagedorn_shape(basis%shape, nsteps, ext_shape)
    call init_hagedorn_basis(ext_basis, ext_shape, basis%q, basis%p, basis%qmat, basis%pmat, basis%actionS, basis%eps)
    call destroy_hagedorn_shape(ext_shape)
  end subroutine init_extended_hagedorn_basis

  subroutine extend_hagedorn_shape(shape, steps, ext_shape)
    type(HagedornBasisShape_t), intent(in) :: shape
    integer, intent(in), optional :: steps
    type(HagedornBasisShape_t), intent(inout) :: ext_shape
    integer :: s, nsteps, kh
    integer, allocatable :: lim(:)

    nsteps = 1
    if (present(steps)) nsteps = steps
    if (nsteps < 0) error stop 'extend_hagedorn_shape: steps must be non-negative.'

    call destroy_hagedorn_shape(ext_shape)
    if (nsteps == 0) then
      call copy_shape_local(ext_shape, shape)
      return
    end if

    select case(shape%shape_kind)
    case (SHAPE_HYPERCUBIC)
      allocate(lim(shape%ndim))
      lim = shape%limits + nsteps
      call init_hypercubic_shape(ext_shape, lim)
    case (SHAPE_SIMPLEX)
      call init_simplex_shape(ext_shape, shape%ndim, shape%nmax + nsteps)
    case (SHAPE_HYPERBOLIC)
      kh = shape%k_hyp
      do s = 1, nsteps
        if (shape%ndim > 1) then
          kh = (2**(shape%ndim-1)) * kh
        else
          kh = kh + 1
        end if
      end do
      call init_hyperbolic_shape(ext_shape, shape%ndim, kh)
    case default
      error stop 'extend_hagedorn_shape: unsupported shape kind.'
    end select
  end subroutine extend_hagedorn_shape

  subroutine evaluate_ground_state(basis, points, phi0, include_prefactor, include_phase)
    type(HagedornBasis_t), intent(in) :: basis
    real(KIND=Rkind), intent(in) :: points(:,:)
    complex(KIND=Rkind), allocatable, intent(out) :: phi0(:)
    logical, intent(in), optional :: include_prefactor, include_phase

    logical :: with_pref, with_phase
    integer :: npts, ipt
    complex(KIND=Rkind), allocatable :: dx(:)
    complex(KIND=Rkind) :: exponent, pref

    if (size(points,1) /= basis%ndim) error stop 'evaluate_ground_state: point dimension mismatch.'

    with_pref = .true.
    with_phase = .true.
    if (present(include_prefactor)) with_pref = include_prefactor
    if (present(include_phase))     with_phase = include_phase

    npts = size(points,2)
    allocate(phi0(npts), dx(basis%ndim))

    pref = (PI * basis%eps**2)**(-FOURTH * real(basis%ndim,KIND=Rkind))
    if (with_pref) pref = pref / basis%sqrt_detQ

    do ipt = 1, npts
      dx = cmplx(points(:,ipt), ZERO, KIND=Rkind) - basis%q
      exponent = HALF * dot_no_conjg(dx, matmul(basis%apq, dx)) + dot_no_conjg(basis%p, dx)
      if (with_phase) exponent = exponent + basis%actionS
      phi0(ipt) = pref * exp(EYE * exponent / basis%eps**2)
    end do
  end subroutine evaluate_ground_state

  subroutine evaluate_basis_on_grid(basis, points, phi, include_prefactor, include_phase)
    !!---------------------------------------------------------------------
    !! Evaluate every basis function φ_k on an arbitrary real grid.
    !! The recursion follows the WaveBlocksND implementation and is exact for
    !! a fixed parameter set (q,p,Q,P,S) and a given basis shape.
    !!---------------------------------------------------------------------
    type(HagedornBasis_t), intent(in) :: basis
    real(KIND=Rkind), intent(in) :: points(:,:)
    complex(KIND=Rkind), allocatable, intent(out) :: phi(:,:)
    logical, intent(in), optional :: include_prefactor, include_phase

    integer :: npts, idx, d, j, parent_idx, child_degree, max_degree
    integer, allocatable :: k(:), kparent(:)
    complex(KIND=Rkind), allocatable :: phi0(:)
    complex(KIND=Rkind), allocatable :: p1(:,:), phim(:,:), t1(:), t2(:)
    complex(KIND=Rkind), allocatable :: dx(:,:)
    real(KIND=Rkind) :: denom

    if (basis%zero_index <= 0) error stop 'evaluate_basis_on_grid: zero multi-index not found in shape.'
    if (size(points,1) /= basis%ndim) error stop 'evaluate_basis_on_grid: point dimension mismatch.'

    npts = size(points,2)
    allocate(phi(basis%basis_size, npts))
    phi = CZERO

    call evaluate_ground_state(basis, points, phi0, include_prefactor, include_phase)
    phi(basis%zero_index, :) = phi0

    allocate(dx(basis%ndim, npts))
    dx = cmplx(points, ZERO, KIND=Rkind) - spread(basis%q, dim=2, ncopies=npts)

    allocate(k(basis%ndim), kparent(basis%ndim), p1(basis%ndim,npts), phim(basis%ndim,npts), t1(npts), t2(npts))
    max_degree = maxval(basis%degree)

    do child_degree = 1, max_degree
      do idx = 1, basis%basis_size
        if (basis%degree(idx) /= child_degree) cycle
        k = basis%shape%nodes(:, idx)
        d = smallest_positive_component(k)
        if (d <= 0) cycle

        parent_idx = basis%backward(d, idx)
        if (parent_idx <= 0) error stop 'evaluate_basis_on_grid: missing parent index in recursion.'
        kparent = basis%shape%nodes(:, parent_idx)

        p1 = dx * spread(phi(parent_idx,:), dim=1, ncopies=basis%ndim)
        phim = CZERO
        do j = 1, basis%ndim
          if (kparent(j) > 0) then
            phim(j,:) = sqrt(real(kparent(j),KIND=Rkind)) * phi(basis%backward(j,parent_idx), :)
          end if
        end do

        t1 = sum(spread(basis%qinv(d,:), dim=2, ncopies=npts) * p1, dim=1)
        t1 = sqrt(TWO / basis%eps**2) * t1
        t2 = sum(spread(basis%qqbar(d,:), dim=2, ncopies=npts) * phim, dim=1)

        denom = sqrt(real(k(d), KIND=Rkind))
        phi(idx,:) = (t1 - t2) / denom
      end do
    end do
  end subroutine evaluate_basis_on_grid

  subroutine evaluate_wavepacket_on_grid(basis, coeff, points, psi, include_prefactor, include_phase)
    type(HagedornBasis_t), intent(in) :: basis
    complex(KIND=Rkind), intent(in) :: coeff(:)
    real(KIND=Rkind), intent(in) :: points(:,:)
    complex(KIND=Rkind), allocatable, intent(out) :: psi(:)
    logical, intent(in), optional :: include_prefactor, include_phase

    complex(KIND=Rkind), allocatable :: phi(:,:)

    if (size(coeff) /= basis%basis_size) error stop 'evaluate_wavepacket_on_grid: coefficient vector has wrong size.'
    call evaluate_basis_on_grid(basis, points, phi, include_prefactor, include_phase)
    allocate(psi(size(points,2)))
    psi = matmul(coeff, phi)
  end subroutine evaluate_wavepacket_on_grid

  subroutine apply_position_operator(basis, coeff, ext_basis, coeff_x)
    !!---------------------------------------------------------------------
    !! Apply the position operator x to a packet ψ = Σ_k c_k φ_k.
    !!
    !! Output coefficients are stored column-wise:
    !!   coeff_x(:,i)  represents  (x_i ψ)  in the extended basis.
    !!---------------------------------------------------------------------
    type(HagedornBasis_t), intent(in) :: basis
    complex(KIND=Rkind), intent(in) :: coeff(:)
    type(HagedornBasis_t), intent(inout) :: ext_basis
    complex(KIND=Rkind), allocatable, intent(out) :: coeff_x(:,:)

    integer :: idx, d, i, ie0, iem, iep
    integer :: kd
    integer, allocatable :: k(:), km(:), kp(:)
    complex(KIND=Rkind) :: cval, fac

    if (size(coeff) /= basis%basis_size) error stop 'apply_position_operator: coefficient vector has wrong size.'

    call init_extended_hagedorn_basis(ext_basis, basis, 1)
    allocate(coeff_x(ext_basis%basis_size, basis%ndim))
    coeff_x = CZERO
    allocate(k(basis%ndim), km(basis%ndim), kp(basis%ndim))

    fac = sqrt(basis%eps**2 / TWO)

    do idx = 1, basis%basis_size
      cval = coeff(idx)
      if (abs(cval) == ZERO) cycle
      k = basis%shape%nodes(:, idx)
      ie0 = find_multiindex(ext_basis%shape, k)
      coeff_x(ie0,:) = coeff_x(ie0,:) + cval * basis%q

      do d = 1, basis%ndim
        kd = k(d)
        if (kd > 0) then
          km = k
          km(d) = km(d) - 1
          iem = find_multiindex(ext_basis%shape, km)
          do i = 1, basis%ndim
            coeff_x(iem,i) = coeff_x(iem,i) + fac * sqrt(real(kd,KIND=Rkind)) * cval * conjg(basis%qmat(i,d))
          end do
        end if

        kp = k
        kp(d) = kp(d) + 1
        iep = find_multiindex(ext_basis%shape, kp)
        do i = 1, basis%ndim
          coeff_x(iep,i) = coeff_x(iep,i) + fac * sqrt(real(kd+1,KIND=Rkind)) * cval * basis%qmat(i,d)
        end do
      end do
    end do
  end subroutine apply_position_operator

  subroutine apply_momentum_operator(basis, coeff, ext_basis, coeff_p)
    !!---------------------------------------------------------------------
    !! Apply the momentum operator p̂ = -i ε² ∇.
    !! Output layout matches apply_position_operator.
    !!---------------------------------------------------------------------
    type(HagedornBasis_t), intent(in) :: basis
    complex(KIND=Rkind), intent(in) :: coeff(:)
    type(HagedornBasis_t), intent(inout) :: ext_basis
    complex(KIND=Rkind), allocatable, intent(out) :: coeff_p(:,:)

    integer :: idx, d, i, ie0, iem, iep
    integer :: kd
    integer, allocatable :: k(:), km(:), kp(:)
    complex(KIND=Rkind) :: cval, fac

    if (size(coeff) /= basis%basis_size) error stop 'apply_momentum_operator: coefficient vector has wrong size.'

    call init_extended_hagedorn_basis(ext_basis, basis, 1)
    allocate(coeff_p(ext_basis%basis_size, basis%ndim))
    coeff_p = CZERO
    allocate(k(basis%ndim), km(basis%ndim), kp(basis%ndim))

    fac = sqrt(basis%eps**2 / TWO)

    do idx = 1, basis%basis_size
      cval = coeff(idx)
      if (abs(cval) == ZERO) cycle
      k = basis%shape%nodes(:, idx)
      ie0 = find_multiindex(ext_basis%shape, k)
      coeff_p(ie0,:) = coeff_p(ie0,:) + cval * basis%p

      do d = 1, basis%ndim
        kd = k(d)
        if (kd > 0) then
          km = k
          km(d) = km(d) - 1
          iem = find_multiindex(ext_basis%shape, km)
          do i = 1, basis%ndim
            coeff_p(iem,i) = coeff_p(iem,i) + fac * sqrt(real(kd,KIND=Rkind)) * cval * conjg(basis%pmat(i,d))
          end do
        end if

        kp = k
        kp(d) = kp(d) + 1
        iep = find_multiindex(ext_basis%shape, kp)
        do i = 1, basis%ndim
          coeff_p(iep,i) = coeff_p(iep,i) + fac * sqrt(real(kd+1,KIND=Rkind)) * cval * basis%pmat(i,d)
        end do
      end do
    end do
  end subroutine apply_momentum_operator

  subroutine apply_gradient_operator(basis, coeff, ext_basis, coeff_grad)
    type(HagedornBasis_t), intent(in) :: basis
    complex(KIND=Rkind), intent(in) :: coeff(:)
    type(HagedornBasis_t), intent(inout) :: ext_basis
    complex(KIND=Rkind), allocatable, intent(out) :: coeff_grad(:,:)

    call apply_momentum_operator(basis, coeff, ext_basis, coeff_grad)
    coeff_grad = (EYE / basis%eps**2) * coeff_grad
  end subroutine apply_gradient_operator

  subroutine apply_second_derivative_operator(basis, coeff, ext2_basis, coeff_hess)
    !!---------------------------------------------------------------------
    !! Analytic Hessian in coefficient space.
    !!
    !! coeff_hess(:,i,j) stores ∂²ψ / (∂x_i ∂x_j) represented in a twice-
    !! extended Hagedorn basis.
    !!---------------------------------------------------------------------
    type(HagedornBasis_t), intent(in) :: basis
    complex(KIND=Rkind), intent(in) :: coeff(:)
    type(HagedornBasis_t), intent(inout) :: ext2_basis
    complex(KIND=Rkind), allocatable, intent(out) :: coeff_hess(:,:,:)

    type(HagedornBasis_t) :: ext1_basis, tmp_basis
    complex(KIND=Rkind), allocatable :: coeff_p(:,:), coeff_pp(:,:)
    integer :: j

    call apply_momentum_operator(basis, coeff, ext1_basis, coeff_p)
    call init_extended_hagedorn_basis(ext2_basis, ext1_basis, 1)
    allocate(coeff_hess(ext2_basis%basis_size, basis%ndim, basis%ndim))
    coeff_hess = CZERO

    do j = 1, basis%ndim
      call apply_momentum_operator(ext1_basis, coeff_p(:,j), tmp_basis, coeff_pp)
      coeff_hess(:, :, j) = -(ONE / basis%eps**4) * coeff_pp
      call destroy_hagedorn_basis(tmp_basis)
      if (allocated(coeff_pp)) deallocate(coeff_pp)
    end do

    call destroy_hagedorn_basis(ext1_basis)
    if (allocated(coeff_p)) deallocate(coeff_p)
  end subroutine apply_second_derivative_operator

  subroutine apply_laplacian_operator(basis, coeff, ext2_basis, coeff_lap)
    type(HagedornBasis_t), intent(in) :: basis
    complex(KIND=Rkind), intent(in) :: coeff(:)
    type(HagedornBasis_t), intent(inout) :: ext2_basis
    complex(KIND=Rkind), allocatable, intent(out) :: coeff_lap(:)

    complex(KIND=Rkind), allocatable :: coeff_hess(:,:,:)
    integer :: d

    call apply_second_derivative_operator(basis, coeff, ext2_basis, coeff_hess)
    allocate(coeff_lap(ext2_basis%basis_size))
    coeff_lap = CZERO
    do d = 1, basis%ndim
      coeff_lap = coeff_lap + coeff_hess(:,d,d)
    end do
  end subroutine apply_laplacian_operator

  subroutine evaluate_gradient_on_grid(basis, coeff, points, grad_psi)
    type(HagedornBasis_t), intent(in) :: basis
    complex(KIND=Rkind), intent(in) :: coeff(:)
    real(KIND=Rkind), intent(in) :: points(:,:)
    complex(KIND=Rkind), allocatable, intent(out) :: grad_psi(:,:)

    type(HagedornBasis_t) :: ext_basis
    complex(KIND=Rkind), allocatable :: coeff_grad(:,:), phi(:,:)

    call apply_gradient_operator(basis, coeff, ext_basis, coeff_grad)
    call evaluate_basis_on_grid(ext_basis, points, phi)
    allocate(grad_psi(size(points,2), basis%ndim))
    grad_psi = transpose(matmul(transpose(coeff_grad), phi))
  end subroutine evaluate_gradient_on_grid

  subroutine evaluate_hessian_on_grid(basis, coeff, points, hess_psi)
    type(HagedornBasis_t), intent(in) :: basis
    complex(KIND=Rkind), intent(in) :: coeff(:)
    real(KIND=Rkind), intent(in) :: points(:,:)
    complex(KIND=Rkind), allocatable, intent(out) :: hess_psi(:,:,:)

    type(HagedornBasis_t) :: ext2_basis
    complex(KIND=Rkind), allocatable :: coeff_hess(:,:,:), phi(:,:)
    integer :: i, j, npts

    call apply_second_derivative_operator(basis, coeff, ext2_basis, coeff_hess)
    call evaluate_basis_on_grid(ext2_basis, points, phi)

    npts = size(points,2)
    allocate(hess_psi(npts, basis%ndim, basis%ndim))
    hess_psi = CZERO
    do j = 1, basis%ndim
      do i = 1, basis%ndim
        hess_psi(:,i,j) = matmul(coeff_hess(:,i,j), phi)
      end do
    end do
  end subroutine evaluate_hessian_on_grid

  subroutine evaluate_laplacian_on_grid(basis, coeff, points, lap_psi)
    type(HagedornBasis_t), intent(in) :: basis
    complex(KIND=Rkind), intent(in) :: coeff(:)
    real(KIND=Rkind), intent(in) :: points(:,:)
    complex(KIND=Rkind), allocatable, intent(out) :: lap_psi(:)

    type(HagedornBasis_t) :: ext2_basis
    complex(KIND=Rkind), allocatable :: coeff_lap(:), phi(:,:)

    call apply_laplacian_operator(basis, coeff, ext2_basis, coeff_lap)
    call evaluate_basis_on_grid(ext2_basis, points, phi)
    allocate(lap_psi(size(points,2)))
    lap_psi = matmul(coeff_lap, phi)
  end subroutine evaluate_laplacian_on_grid

  subroutine project_coefficients(source_basis, target_basis, source_coeff, target_coeff)
    !!---------------------------------------------------------------------
    !! Truncate or restrict coefficients from one shape to another by keeping
    !! only common multi-indices. This is the natural projection used after an
    !! operator has been applied in an extended basis.
    !!---------------------------------------------------------------------
    type(HagedornBasis_t), intent(in) :: source_basis, target_basis
    complex(KIND=Rkind), intent(in) :: source_coeff(:)
    complex(KIND=Rkind), allocatable, intent(out) :: target_coeff(:)

    integer :: it, is

    if (size(source_coeff) /= source_basis%basis_size) error stop 'project_coefficients: bad source size.'
    allocate(target_coeff(target_basis%basis_size))
    target_coeff = CZERO

    do it = 1, target_basis%basis_size
      is = find_multiindex(source_basis%shape, target_basis%shape%nodes(:,it))
      if (is > 0) target_coeff(it) = source_coeff(is)
    end do
  end subroutine project_coefficients

  subroutine embed_coefficients(source_basis, target_basis, source_coeff, target_coeff)
    type(HagedornBasis_t), intent(in) :: source_basis, target_basis
    complex(KIND=Rkind), intent(in) :: source_coeff(:)
    complex(KIND=Rkind), allocatable, intent(out) :: target_coeff(:)

    integer :: is, it

    if (size(source_coeff) /= source_basis%basis_size) error stop 'embed_coefficients: bad source size.'
    allocate(target_coeff(target_basis%basis_size))
    target_coeff = CZERO
    do is = 1, source_basis%basis_size
      it = find_multiindex(target_basis%shape, source_basis%shape%nodes(:,is))
      if (it > 0) target_coeff(it) = source_coeff(is)
    end do
  end subroutine embed_coefficients

  subroutine copy_shape_local(dst, src)
    type(HagedornBasisShape_t), intent(inout) :: dst
    type(HagedornBasisShape_t), intent(in) :: src

    call destroy_hagedorn_shape(dst)
    dst%ndim = src%ndim
    dst%shape_kind = src%shape_kind
    dst%nmax = src%nmax
    dst%k_hyp = src%k_hyp
    dst%basis_size = src%basis_size
    if (allocated(src%limits)) then
      allocate(dst%limits(size(src%limits)))
      dst%limits = src%limits
    end if
    if (allocated(src%nodes)) then
      allocate(dst%nodes(size(src%nodes,1), size(src%nodes,2)))
      dst%nodes = src%nodes
    end if
  end subroutine copy_shape_local

  subroutine build_neighbour_tables(basis)
    type(HagedornBasis_t), intent(inout) :: basis
    integer :: idx, d
    integer, allocatable :: k(:), km(:), kp(:), z(:)

    allocate(basis%degree(basis%basis_size), &
             basis%backward(basis%ndim,basis%basis_size), &
             basis%forward(basis%ndim,basis%basis_size))
    basis%backward = 0
    basis%forward = 0

    allocate(k(basis%ndim), km(basis%ndim), kp(basis%ndim), z(basis%ndim))
    z = 0
    basis%zero_index = find_multiindex(basis%shape, z)

    do idx = 1, basis%basis_size
      k = basis%shape%nodes(:, idx)
      basis%degree(idx) = sum(k)
      do d = 1, basis%ndim
        km = k
        kp = k
        if (k(d) > 0) then
          km(d) = km(d) - 1
          basis%backward(d,idx) = find_multiindex(basis%shape, km)
        end if
        kp(d) = kp(d) + 1
        basis%forward(d,idx) = find_multiindex(basis%shape, kp)
      end do
    end do
  end subroutine build_neighbour_tables

  pure function smallest_positive_component(k) result(pos)
    integer, intent(in) :: k(:)
    integer :: pos, d
    pos = 0
    do d = 1, size(k)
      if (k(d) > 0) then
        pos = d
        return
      end if
    end do
  end function smallest_positive_component

  pure function dot_no_conjg(x, y) result(val)
    complex(KIND=Rkind), intent(in) :: x(:), y(:)
    complex(KIND=Rkind) :: val
    integer :: i
    val = CZERO
    do i = 1, size(x)
      val = val + x(i) * y(i)
    end do
  end function dot_no_conjg


  subroutine Cmat_to_QP(Cmat, Qmat, Pmat)
    complex(KIND=Rkind), intent(in) :: Cmat(:,:)
    complex(KIND=Rkind), allocatable, intent(out) :: Qmat(:,:), Pmat(:,:)

    integer :: ndim
    complex(KIND=Rkind), allocatable :: ImC(:,:), sqrtImC(:,:)

    ndim = size(Cmat,1)
    if (size(Cmat,2) /= ndim) error stop 'Cmat_to_QP: matrix must be square.'

    allocate(ImC(ndim,ndim))
    ImC = (Cmat - conjg(transpose(Cmat))) / (TWO*EYE)

    sqrtImC = matrix_sqrt_hermitian(ImC)
    Qmat = matrix_inverse_c(sqrtImC)

    allocate(Pmat(ndim,ndim))
    Pmat = matmul(Cmat,Qmat)
  end subroutine Cmat_to_QP



